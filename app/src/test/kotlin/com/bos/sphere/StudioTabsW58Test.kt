/**
 * Wave 58 (studioPreview), CFG-70: Liftoff Studio's six tabs and their sections are the app's. The Studio schema (generated by core-data
 * `StudioSchemaW56Test` from `SettingsTabLayout.kt`) names, for every field, the app row that edits it; here, over the real built Settings:
 *  - the tab and section Studio shows each field in are the ones `SettingsTabLayout` places that row in, and the section lists are the same;
 *  - every row Studio names is really built (in one of a few home configurations);
 *  - the rows' own setters: flipping every switch, choice and stepper of the built Settings (with a recording `updatePrefs`) changes only
 *    export keys whose Studio field sits in that row's tab and section. So a row moved in the app, or a Studio field mapped to the wrong row,
 *    fails here.
 */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34])
class StudioTabsW58Test {
    @Before fun setUp() { L10n.setLanguage("en") }

    private var recorded: ((LauncherPrefs) -> LauncherPrefs)? = null

    private fun model(p: LauncherPrefs, pages: Int = 3) = SettingsModel(
        prefs = p, updatePrefs = { f -> recorded = f }, pageIndex = 1,
        pages = (1..pages).map { HomePage(keys = emptyList(), id = it.toLong(), layout = PageLayout(shape = PageShape.Grid)) },
        setPageLayout = { _, _ -> }, addPageAfter = {}, deletePage = {}, setClockTile = { _, _ -> },
        corners = emptyMap(), gestures = emptyMap(), setGesture = { _, _ -> },
        about = listOf("Version" to "test"), appsByKey = emptyMap(), isLandscape = false, chosenApp = { null },
        pickLeftWidget = {}, leftWidgetLabel = null, pickAppFor = {}, motionAvailable = true, editCorner = {}, editGesture = {},
        system = SystemLinks({}, {}, {}, {}), capabilities = emptyList(),
        lab = listOf(LabEntry("spike", "Frame spike", "ok", null)), restorePages = {},
        hiddenApps = HiddenAppsAccess(count = 2, hiddenKeys = kotlinx.coroutines.flow.MutableStateFlow(emptySet()), allApps = emptyList(), setHidden = { _, _ -> }),
    )

    /** Home configurations that between them build every conditional row. */
    private val states = listOf(
        LauncherPrefs(homePages = HomePages.Paginated, leftPage = LeftPage.Widget, leftWidgetId = 3, hotCornersOn = true, settingsBackdrop = SettingsBackdrop.Wallpaper, calmStyle = CalmStyle.entries.first { it.ambient }),
        LauncherPrefs(homePages = HomePages.Continuous, rightSide = RightSide.RecentsPanel, motionEnabled = true, adaptiveGrid = true, badgesOn = true),
        LauncherPrefs(),
    )

    private val studioTabIds = mapOf("home" to SettingsTabs.HOME, "look" to SettingsTabs.LOOK, "apps" to SettingsTabs.APPS, "radar" to SettingsTabs.RADAR, "side" to SettingsTabs.SIDE_PANEL, "system" to SettingsTabs.SYSTEM)

    private fun root(): File { var d: File? = File("").absoluteFile; while (d != null && !File(d, "web/liftoff-studio").isDirectory) d = d.parentFile; return d!! }
    private val schema by lazy { JSONObject(File(root(), "web/liftoff-studio/schema.json").readText()) }
    private class F(val key: String, val tab: String, val group: String, val row: String, val scope: String)
    private val fields by lazy { schema.getJSONArray("fields").let { a -> List(a.length()) { a.getJSONObject(it) }.map { F(it.getString("key"), it.getString("tab"), it.getString("group"), it.getString("row"), it.getString("scope")) } } }

    @Test fun CFG_70_everyStudioFieldSitsInTheTabAndSectionTheAppPlacesItsRowIn() {
        val wrong = fields.mapNotNull { f ->
            val at = SettingsTabLayout.whereIs(f.row) ?: return@mapNotNull "${f.key}: the row ${f.row} is not in SettingsTabLayout"
            val want = studioTabIds.getValue(f.tab) to f.group
            if (at != want) "${f.key}: Studio shows it in ${want.first} > ${want.second}, the app in ${at.first} > ${at.second}" else null
        }
        assertEquals(emptyList<String>(), wrong)
        // the same tabs and sections, in the same order
        val tabs = schema.getJSONArray("tabs")
        assertEquals(SettingsTabs.KEYS, List(tabs.length()) { studioTabIds.getValue(tabs.getJSONObject(it).getString("id")) })
        for (i in 0 until tabs.length()) {
            val t = tabs.getJSONObject(i); val s = t.getJSONArray("sections")
            assertEquals(t.getString("id"), SettingsTabLayout.TABS[i].sections.map { it.header }, List(s.length()) { s.getString(it) })
            assertEquals(SettingsTabLayout.TABS[i].key.uppercase(), t.getString("label"))
        }
    }

    @Test fun CFG_70_everyRowStudioNamesIsReallyBuilt() {
        val built = states.flatMap { p -> SettingsTabLayout.place(buildSettingsTopics(model(p))).placedKeys.values.flatten() }.toSet()
        val missing = fields.map { it.row }.distinct().filter { r -> if (r.endsWith("/" + SettingsTabLayout.ALL)) built.none { it.startsWith(r.dropLast(1)) } else r !in built }
        assertEquals("rows Studio names that the app never builds", emptyList<String>(), missing)
    }

    @Test fun CFG_70_theRowsOwnSettersChangeOnlyFieldsStudioShowsInThatRowsSection() {
        // Topics whose rows write stores other than launcher_prefs (Comms, sound, the dock, profiles): not called, so nothing leaks into other tests.
        val skip = setOf(SettingsTabLayout.T_SIDE, SettingsTabLayout.T_SOUND, SettingsTabLayout.T_SYSTEM, SettingsTabLayout.T_CAPS, SettingsTabLayout.T_LAB, SettingsTabLayout.T_HIDDEN,
            SettingsTabLayout.T_BACKUP, SettingsTabLayout.T_WORKSPACES, SettingsTabLayout.T_DESKTOP, SettingsTabLayout.T_ABOUT)
        val byKey = fields.filter { it.scope == "settings" }.associateBy { it.key }
        val reachedFrom = LinkedHashMap<String, MutableSet<Pair<String, String>>>()
        for (p in states) {
            val topics = buildSettingsTopics(model(p))
            val placed = SettingsTabLayout.place(topics)
            val where = IdentityHashMap<SettingItem, Pair<String, String>>()
            placed.tabs.forEachIndexed { ti, tab ->
                var header = ""
                tab.items.forEachIndexed { i, item -> tab.headers[i]?.let { header = it }; where[item] = SettingsTabs.KEYS[ti] to header }
            }
            val before = SettingsCodec.encode(p).getJSONObject("prefs")
            for (c in topics) {
                if (SettingsTabLayout.topicOf(c) in skip) continue
                for (item in c.items) {
                    val calls: List<() -> Unit> = when (item) {
                        is SettingItem.Toggle -> listOf({ item.onChange(!item.checked) })
                        is SettingItem.Choice<*> -> {
                            @Suppress("UNCHECKED_CAST") val ch = item as SettingItem.Choice<Any?>
                            ch.options.filter { it != ch.selected }.take(2).map { o -> { ch.onSelect(o) } }
                        }
                        is SettingItem.Stepper -> listOf({ item.onChange(if (item.count < item.range.last) item.count + item.step.coerceAtLeast(1) else item.count - 1) })
                        is SettingItem.Slider -> listOf({ item.onChange(if (item.amount < item.range.endInclusive - 0.1f) item.amount + 0.1f else item.amount - 0.1f) })
                        else -> emptyList()
                    }
                    for (call in calls) {
                        recorded = null
                        call()
                        val after = recorded?.invoke(p)?.let { SettingsCodec.encode(it).getJSONObject("prefs") } ?: continue
                        val changed = (before.keys().asSequence() + after.keys().asSequence()).toSet().filter { k -> before.opt(k)?.toString() != after.opt(k)?.toString() }
                        val at = where[item] ?: continue
                        for (k in changed) if (k in byKey) reachedFrom.getOrPut(k) { LinkedHashSet() } += at
                    }
                }
            }
        }
        // A row may change a second key on the way (choosing a Radar layout also unpins it): the key's Studio section must be one of the sections whose rows change it.
        val wrong = reachedFrom.mapNotNull { (k, at) ->
            val f = byKey.getValue(k); val want = studioTabIds.getValue(f.tab) to f.group
            if (want !in at) "$k is shown by Studio in ${want.first} > ${want.second}, but the rows that change it are in ${at.joinToString { "${it.first} > ${it.second}" }}" else null
        }
        assertEquals(emptyList<String>(), wrong)
        assertTrue("the setters reached only ${reachedFrom.size} Studio fields", reachedFrom.size >= 40)
    }
}
