#!/usr/bin/env node
// C0 fidelity fence. Evaluates the prototype's OWN source (docs/spherelauncher13.html) -- magAtF,
// txAtF, render(), renderGlobe() and the globe item construction -- inside a vm with a stubbed DOM,
// and writes reference vectors to fixtures/sphere-vectors.json. Never hand-edit the output.
// Usage: node tools/gen_sphere_vectors.js [--check]   (--check fails if the file would change)
"use strict";
const fs = require("fs"), path = require("path"), vm = require("vm"), crypto = require("crypto");
const root = path.resolve(__dirname, "..");
const htmlPath = path.join(root, "docs", "spherelauncher13.html");
const outPath = path.join(root, "fixtures", "sphere-vectors.json");
const html = fs.readFileSync(htmlPath, "utf8");

function line(re, what) {
  const m = html.split("\n").find(l => re.test(l));
  if (!m) throw new Error("prototype line not found: " + what);
  return m;
}
function fn(name) {
  const start = html.indexOf("function " + name + "(");
  if (start < 0) throw new Error("function not found: " + name);
  const end = html.indexOf("\n}\n", start);
  return html.slice(start, end + 2);
}
if (!/range=6,/.test(html)) throw new Error("prototype no longer has range=6; update the generator");

const prelude = [
  line(/^const P = \{/, "P"),
  line(/^const STEP_DEG=/, "STEP_DEG"),
  line(/^const DEG=Math\.PI/, "DEG/clamp/smooth01"),
  line(/^const POOL=/, "POOL"),
  line(/^const APPS_ALL=/, "APPS_ALL"),
  line(/^function magAtF/, "magAtF"),
  line(/^function txAtF/, "txAtF"),
  line(/^const GA=/, "GA/NA"),
  line(/^const gitems=/, "gitems"),
  fn("render"), fn("renderGlobe"),
].join("\n");

const stubEl = () => ({ style: {}, classList: { toggle() {}, remove() {}, add() {} }, set innerHTML(v) {} });
const script = `
let range=6, n=15, pos=0, portrait=false, rowMode='auto', zoom=0, yaw=0, pitch=0, Wv=400, Hv=800, hticks=[];
const curRows=()=>rowMode==='1'?1:rowMode==='2'?2:(portrait?2:1);
const maxIdx=()=>(curRows()===2?Math.ceil(n/2):n)-1;
const els=Array.from({length:n},()=>stubEl()), contact=stubEl(), globe=stubEl(), glabel=stubEl();
const document={createElement:()=>stubEl()}; globe.appendChild=()=>{}; const svg=()=>''; const I=new Proxy({},{get:()=>''});
${prelude}
const out={meta:{}, lens:[], cards:[], globe:[]};
out.meta={range, STEP_DEG, P:Object.assign({},P), appCount:n, globeCount:NA};
for (const foc of [1, 1.2, P.focus, 1+(P.focus-1)*0.45])
  for (const o of [-8,-6.8,-6,-3.5,-1,-0.25,0,0.25,0.5,1,2.75,5.4,6,6.8,8])
    out.lens.push({foc, o, mag:magAtF(o,foc), tx:txAtF(o,foc)});
const parse = t => { const g=/translate3d\\(([-\\d.]+)px, ([-\\d.]+)px, ([-\\d.]+)px\\) rotateY\\(([-\\d.]+)deg\\) rotateX\\(([-\\d.]+)deg\\) scale\\(([-\\d.]+)\\)/.exec(t); return g.slice(1).map(Number); };
for (const rm of ['1','2']) { rowMode=rm;
  for (const p of [0, 0.4, 3, 7, 10.5, 14]) { pos=p; render();
    els.forEach((e,i)=>{ const hidden=e.style.display==='none';
      const rec={rows:curRows(), pos:p, i, hidden};
      if(!hidden){ const [tx,ty,tz,rotY,rotX,scale]=parse(e.style.transform); Object.assign(rec,{tx,ty,tz,rotY,rotX,scale,zIndex:e.style.zIndex}); }
      out.cards.push(rec); }); } }
for (const [y,pi,z,W,H] of [[0,0,1,400,800],[0.7,0.3,1,400,800],[-1.9,1.2,0.6,360,720],[3.1,-0.9,0.5,800,400],[0.2,0,0.1,400,800]]) {
  yaw=y; pitch=pi; zoom=z; Wv=W; Hv=H; renderGlobe();
  gitems.forEach((g,i)=>{ const hidden=g.el.style.display==='none'; out.globe.push({yaw:y,pitch:pi,zoom:z,W,H,i,
    x:g.x,y:g.y,z:g.z,sx:g.sx,sy:g.sy,pz:g.pz,sc:g.sc,hidden,
    ...(hidden?{}:{opacity:Number(g.el.style.opacity),zIndex:g.el.style.zIndex})}); }); }
out;
`;
const ctx = vm.createContext({ Math, stubEl, Object, Array, Proxy, Number });
const out = vm.runInContext(script, ctx);
out.meta.source = "docs/spherelauncher13.html";
out.meta.sourceSha256 = crypto.createHash("sha256").update(html).digest("hex");
out.meta.note = "GENERATED by tools/gen_sphere_vectors.js - do not hand-edit";
const text = JSON.stringify(out, null, 1) + "\n";
if (process.argv.includes("--check")) {
  if (!fs.existsSync(outPath) || fs.readFileSync(outPath, "utf8") !== text) { console.error("fixtures/sphere-vectors.json is stale"); process.exit(1); }
  console.log("fixtures up to date"); process.exit(0);
}
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, text);
console.log(`wrote ${path.relative(root, outPath)}: lens=${out.lens.length} cards=${out.cards.length} globe=${out.globe.length}`);
