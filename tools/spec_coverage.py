#!/usr/bin/env python3
"""Spec section 15: list every requirement ID in docs/Spec.md with the tests whose names start with that ID.

A test counts when it is a Kotlin `fun ID_something` (the ID with '-' written as '_'), as the spec's naming rule says,
found under any src/test or src/androidTest directory. Writes docs/TEST_COVERAGE.md. Works on whatever is present.
Usage: python3 tools/spec_coverage.py [--check]   (--check exits 1 when an M or S requirement has no test)
"""
import re, sys, pathlib, datetime

ROOT = pathlib.Path(__file__).resolve().parent.parent
spec = (ROOT / "docs/Spec.md").read_text(encoding="utf-8")
status_file = ROOT / "docs/SPEC_STATUS.md"

ID_RE = re.compile(r"\b([A-Z]{3}-\d{2})\b")
# Priority: table rows in the status file are "| ID | P | status | note |"; spec rows carry "(M)" or "| M |".
prio = {}
if status_file.exists():
    for m in re.finditer(r"^\|\s*([A-Z]{3}-\d{2})\s*\|\s*([MSC])\s*\|", status_file.read_text(encoding="utf-8"), re.M):
        prio[m.group(1)] = m.group(2)
for m in re.finditer(r"\*\*([A-Z]{3}-\d{2})\.?\*\*[^\n]*?\(([MSC])\)", spec):
    prio.setdefault(m.group(1), m.group(2))
for m in re.finditer(r"^\|\s*([A-Z]{3}-\d{2})\s*\|[^\n]*?\|\s*([MSC])\s*\|", spec, re.M):
    prio.setdefault(m.group(1), m.group(2))

PREFIXES = ("PAL", "INP", "HOM", "DCK", "WSP", "EXT", "STR", "CFG", "NFR", "ELV", "SPK")
ids = sorted({i for i in ID_RE.findall(spec) if i.split("-")[0] in PREFIXES and not i.startswith("SPK")})

tests = {}  # id -> list of (file, name)
fun_re = re.compile(r"\bfun\s+`?(([A-Z]{3})[_-](\d{2})(?:_to([A-Z]{3})_(\d{2}))?[_A-Za-z0-9 ,.()-]*)")
for f in sorted(ROOT.rglob("*.kt")):
    parts = f.relative_to(ROOT).parts
    if "build" in parts or not any(p in ("test", "androidTest") for p in parts):
        continue
    for m in fun_re.finditer(f.read_text(encoding="utf-8", errors="replace")):
        name = m.group(1).strip()
        # A name may chain several IDs (NFR_03_NFR_04_x covers both) and ranges (NFR_01_toNFR_08_x covers 01..08).
        lead = re.match(r"(?:[A-Z]{3}_\d{2}(?:_to[A-Z]{3}_\d{2})?_?)+", name).group(0)
        for t in re.finditer(r"([A-Z]{3})_(\d{2})(?:_to([A-Z]{3})_(\d{2}))?", lead):
            lo = int(t.group(2))
            hi = int(t.group(4)) if t.group(4) and t.group(3) == t.group(1) else lo
            for n in range(lo, hi + 1):
                entry = (str(f.relative_to(ROOT)), name)
                lst = tests.setdefault(f"{t.group(1)}-{n:02d}", [])
                if entry not in lst:
                    lst.append(entry)

lines = ["# Test coverage by requirement ID", "",
         "Generated by `python3 tools/spec_coverage.py` from docs/Spec.md and the test sources. Do not edit by hand.",
         "A test counts for a requirement when its function name starts with the ID (`PAL_07_keyboardOperation` covers PAL-07).",
         "A test existing is not device verification; see docs/SPEC_STATUS.md for status.", ""]
covered = sum(1 for i in ids if i in tests)
ms = [i for i in ids if prio.get(i) in ("M", "S")]
ms_missing = [i for i in ms if i not in tests]
lines += [f"Requirements in the spec: {len(ids)}. With at least one test: {covered}. M or S without a test: {len(ms_missing)}.", "",
          "| ID | P | Tests | Test names |", "| --- | --- | --- | --- |"]
for i in ids:
    t = tests.get(i, [])
    names = "<br>".join(f"`{n}` ({pathlib.Path(p).name})" for p, n in t[:6]) + (f"<br>and {len(t)-6} more" if len(t) > 6 else "")
    lines.append(f"| {i} | {prio.get(i, "-" if i.startswith("ELV") else "?")} | {len(t)} | {names or 'none'} |")
orph = sorted(i for i in tests if i not in ids)
if orph:
    lines += ["", "Tests naming IDs that are not in the spec: " + ", ".join(orph)]
out = ROOT / "docs/TEST_COVERAGE.md"
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"{covered}/{len(ids)} requirements have tests; M/S without tests: {len(ms_missing)}; wrote {out.relative_to(ROOT)}")
if "--check" in sys.argv and ms_missing:
    print("missing:", ", ".join(ms_missing)); sys.exit(1)
